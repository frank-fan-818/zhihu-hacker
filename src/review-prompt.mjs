// 审稿意见的判定标准（提示词内核）。
//
// 为什么单独放一个文件：这份标准同时被三处使用——检查提示词、复核（把材料与原句对比）
// 的提示词、以及 test/review-prompt.test.mjs 的契约测试。写在 service.mjs 里时，
// “什么样的意见算中肯”只存在于一句话里，改了没人能看出来，也没法回归。
//
// 中肯的定义（本项目口径）：
//   1. 说到点上：指名这句话实际主张了什么，缺的到底是哪一环；不写“不够严谨”这类空话。
//   2. 能被接受：先承认作者已经做对的部分，只在真有缺口时报告；作者明说不主张的不算缺口。
//   3. 有用：给得出下一步方向（收窄范围／补条件／补依据／改表述），而不是只判死刑。
//   4. 有分寸：分清关键缺口与可接受的取舍，不把风格偏好、修辞、口头语当论证问题。

