export const num = (v, d) => (Number.isFinite(Number(v)) ? Math.round(Number(v)) : d);
export const oneOf = (v, allowed, fallback) => (allowed.includes(String(v ?? '').trim()) ? String(v).trim() : fallback);
export const short = (v, max) => (typeof v === 'string' && v.trim() ? [...v.trim()].slice(0, max).join('') : '');

